export const businesses: Business[] = site.showSampleContent
  ? allBusinesses
  : allBusinesses.filter((b) => !b.sample);

export function getBusiness(slug: string) {
  return businesses.find((b) => b.slug === slug);
}

/** Featured first, then newest */
export function sortBusinesses(list: Business[]) {
  const tierRank = { featured: 0, plus: 1, community: 2 } as const;
  return [...list].sort(
    (a, b) =>
      Number(!!a.sample) - Number(!!b.sample) ||
      tierRank[a.tier] - tierRank[b.tier] ||
      b.joined.localeCompare(a.joined),
  );
}

export const featuredBusinesses = sortBusinesses(businesses.filter((b) => b.featured || b.tier === "featured"));
